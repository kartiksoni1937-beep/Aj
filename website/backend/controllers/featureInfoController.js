/**
 * serves encoded global strings to clients
 * everything unified into a single global strings system!
 * - Cyde
 */

const fs = require("fs");
const path = require("path");

// XOR seed - MUST match the client or everything breaks
const ENCODING_SEED = 0xEC40;

// encodes strings into XOR'd char arrays, same PRNG as java
const encode = (str, seed) => {
    const result = [];
    let key = seed | 0; // Force 32-bit integer
    for (let i = 0; i < str.length; i++) {
        const charCode = str.charCodeAt(i);
        result.push(charCode ^ (key & 0xFF));
        key = (Math.imul(key, 1103515245) + 12345) | 0;
    }
    return result;
};

const FEATURES_PATH = path.join(__dirname, "..", "resources", "features.json");

// load features.json - generated by the transformer at build time
let GLOBAL_STRINGS = [];

// Function to load features from file
const loadFeatures = () => {
    try {
        const raw = fs.readFileSync(FEATURES_PATH, "utf8");
        const parsed = JSON.parse(raw);
        GLOBAL_STRINGS = parsed.globalStrings || [];
        console.log(`[featureInfoController] Loaded ${GLOBAL_STRINGS.length} global strings from features.json`);
        return true;
    } catch (err) {
        console.error("[featureInfoController] Failed to load features.json", err);
        GLOBAL_STRINGS = [];
        return false;
    }
};

// Initial load
loadFeatures();

// Export reload function
exports.reloadFeatures = loadFeatures;

// encodes all global strings and sends them to the client
// uses minified key "g" to match client expectations
exports.getFragmentedFeatureInfo = () => {
    const result = {
        g: GLOBAL_STRINGS.map((str, index) => {
            // each string gets its own seed so it's harder to reverse
            const stringSeed = (ENCODING_SEED + index * 7919) & 0x7FFFFFFF;
            return encode(str, stringSeed);
        })
    };
    return result;
};

exports.getFeatureCount = () => GLOBAL_STRINGS.length;
exports.ENCODING_SEED = ENCODING_SEED;
